import { execFile } from 'node:child_process';
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

export const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const execFileAsync = promisify(execFile);
const excludedRootHtml = new Set(['index.html', 'demo.html', 'test.html']);

function argValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function hasArg(name) {
  return process.argv.includes(name);
}

export function decodeHtml(value = '') {
  return value
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .trim();
}

export function attr(tag, name) {
  const match = tag.match(new RegExp(`${name}\\s*=\\s*["']([^"']*)["']`, 'i'));
  return match ? decodeHtml(match[1]) : undefined;
}

export function meta(html, name) {
  const tags = html.match(/<meta\s+[^>]*>/gi) || [];
  const tag = tags.find(candidate => attr(candidate, 'name') === name);
  return tag ? attr(tag, 'content') : undefined;
}

export function titleOf(html) {
  const match = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  return match ? decodeHtml(match[1].replace(/\s+/g, ' ')) : undefined;
}

export function parsePresentationDate(value) {
  const match = value?.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/);
  if (!match) return undefined;

  const day = Number(match[1]);
  const month = Number(match[2]);
  const year = Number(match[3]);
  const timestamp = Date.UTC(year, month - 1, day);
  const parsed = new Date(timestamp);

  if (
    parsed.getUTCFullYear() !== year
    || parsed.getUTCMonth() !== month - 1
    || parsed.getUTCDate() !== day
  ) return undefined;

  return timestamp;
}

export function isValidVersion(value) {
  return /^v\d+\.\d+$/i.test(value || '');
}

export function normaliseAttendance(value) {
  if (value === undefined || value === null || value === '' || value === '?') return undefined;
  if (!/^\d+$/.test(String(value).trim())) return undefined;

  const attendance = Number(value);
  return Number.isSafeInteger(attendance) && attendance >= 0 ? attendance : undefined;
}

function yamlString(value) {
  return JSON.stringify(String(value));
}

export function toYaml(presentations) {
  const header = [
    '# Generated from canonical pure-v1 presentation sources at build time.',
    '# Do not edit this file manually.',
    '# Presentation metadata lives in presentation-* meta tags in each source file.',
    ''
  ];

  const body = presentations.flatMap(presentation => {
    const lines = [
      `- name: ${yamlString(presentation.name)}`,
      `  version: ${yamlString(presentation.version)}`,
      `  date: ${yamlString(presentation.date)}`,
      `  url: ${yamlString(presentation.url)}`
    ];
    if (presentation.attendance !== undefined) lines.push(`  attendance: ${presentation.attendance}`);
    lines.push('');
    return lines;
  });

  return [...header, ...body].join('\n');
}

function hasSlidesContainer(html) {
  return /class\s*=\s*["'][^"']*\bslides\b[^"']*["']/i.test(html);
}

export function isCanonicalPresentationSource(html) {
  return meta(html, 'presentation-format') === 'pure-v1' && hasSlidesContainer(html);
}

export async function discoverPresentations({ root = defaultRoot } = {}) {
  const entries = await readdir(root, { withFileTypes: true });
  const presentations = [];
  const errors = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.html') || excludedRootHtml.has(entry.name)) continue;

    const html = await readFile(path.join(root, entry.name), 'utf8');
    if (!hasSlidesContainer(html)) continue;
    if (meta(html, 'presentation-format') !== 'pure-v1') {
      errors.push(`${entry.name}: presentation sources with a .slides container must declare presentation-format="pure-v1".`);
      continue;
    }

    const title = titleOf(html);
    const name = meta(html, 'presentation-name');
    const version = meta(html, 'presentation-version');
    const date = meta(html, 'presentation-date');
    const rawAttendance = meta(html, 'presentation-attendance');

    const missing = [['title', title], ['name', name], ['version', version], ['date', date]]
      .filter(([, value]) => !value).map(([field]) => field);
    if (missing.length) {
      errors.push(`${entry.name}: missing ${missing.join(', ')} in canonical pure-v1 source metadata.`);
      continue;
    }

    if (!isValidVersion(version)) errors.push(`${entry.name}: invalid version ${JSON.stringify(version)}; expected vX.Y (for example v6.2).`);
    const dateTimestamp = parsePresentationDate(date);
    if (dateTimestamp === undefined) errors.push(`${entry.name}: invalid date ${JSON.stringify(date)}; expected a real DD/MM/YYYY calendar date.`);

    const attendance = normaliseAttendance(rawAttendance);
    if (rawAttendance !== undefined && rawAttendance !== '' && rawAttendance !== '?' && attendance === undefined) {
      errors.push(`${entry.name}: invalid attendance ${JSON.stringify(rawAttendance)}; expected a non-negative integer.`);
    }

    if (!isValidVersion(version) || dateTimestamp === undefined || (rawAttendance !== undefined && rawAttendance !== '' && rawAttendance !== '?' && attendance === undefined)) continue;
    presentations.push({ name, version, date, url: entry.name, attendance, dateTimestamp });
  }

  if (errors.length) throw new Error(`Presentation metadata validation failed:\n- ${errors.join('\n- ')}`);
  if (!presentations.length) throw new Error('No canonical pure-v1 presentation sources were discovered.');

  presentations.sort((a, b) => a.dateTimestamp - b.dateTimestamp || a.url.localeCompare(b.url));
  return presentations.map(({ dateTimestamp, ...presentation }) => presentation);
}

export async function buildPure({ root = defaultRoot } = {}) {
  await execFileAsync('npm', ['run', 'pure:preview'], {
    cwd: root,
    env: process.env,
    maxBuffer: 20 * 1024 * 1024
  });
  return path.join(root, 'pure', 'dist');
}

export async function exportSite(outputDir, presentations, {
  root = defaultRoot,
  builtSiteDir = path.join(root, 'pure', 'dist')
} = {}) {
  const resolvedOutput = path.resolve(outputDir);
  const resolvedBuiltSite = path.resolve(builtSiteDir);
  if (resolvedOutput === resolvedBuiltSite || resolvedBuiltSite.startsWith(`${resolvedOutput}${path.sep}`)) {
    throw new Error('Export destination must not contain the Pure build directory.');
  }

  const manifest = JSON.parse(await readFile(path.join(resolvedBuiltSite, 'presentations.json'), 'utf8'));
  const expectedUrls = presentations.map(presentation => presentation.url).sort();
  const builtUrls = manifest.map(presentation => presentation.url).sort();
  if (JSON.stringify(builtUrls) !== JSON.stringify(expectedUrls)) {
    throw new Error(`Pure build presentation set does not match metadata discovery. Expected ${expectedUrls.length}, found ${builtUrls.length}.`);
  }

  await rm(resolvedOutput, { recursive: true, force: true });
  await mkdir(path.dirname(resolvedOutput), { recursive: true });
  await cp(resolvedBuiltSite, resolvedOutput, { recursive: true });

  for (const url of expectedUrls) {
    await readFile(path.join(resolvedOutput, url));
  }
  await readFile(path.join(resolvedOutput, 'build-info.json'));
  await readFile(path.join(resolvedOutput, 'presentations.json'));
}

export async function runCli() {
  const presentations = await discoverPresentations();

  if (hasArg('--check')) console.log(`Validated ${presentations.length} canonical presentation sources.`);

  const manifestPath = argValue('--manifest');
  if (manifestPath) {
    const resolvedManifest = path.resolve(manifestPath);
    await mkdir(path.dirname(resolvedManifest), { recursive: true });
    await writeFile(resolvedManifest, toYaml(presentations), 'utf8');
    console.log(`Generated ${resolvedManifest}`);
  }

  const exportPath = argValue('--export');
  if (exportPath) {
    const builtSiteDir = await buildPure();
    await exportSite(exportPath, presentations, { builtSiteDir });
    console.log(`Exported Pure presentation site to ${path.resolve(exportPath)}`);
  }

  if (!hasArg('--check') && !manifestPath && !exportPath) console.log(toYaml(presentations));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await runCli();
}
